import { useState } from 'react'
import { Anchor, Button, Center, PinInput, Stack, Text } from '@mantine/core'
import { AuthLayout } from './components/AuthLayout'
import { AuthHeader } from './components/AuthHeader'

export interface TwoFactorFormProps {
  code?: string
  isLoading?: boolean
  error?: string
  onCodeChange?: (val: string) => void
  onSubmit?: (e: React.FormEvent) => void
  onUseRecoveryCode?: () => void
}

/**
 * Presentational Two-Factor Authentication Verification Form.
 * Figma: Figma_3_Access.pdf - Frame 2
 */
export function TwoFactorForm({
  code: externalCode,
  isLoading = false,
  error,
  onCodeChange,
  onSubmit,
  onUseRecoveryCode,
}: TwoFactorFormProps) {
  const [internalCode, setInternalCode] = useState('')
  const code = externalCode !== undefined ? externalCode : internalCode

  const handleCodeChange = (val: string) => {
    setInternalCode(val)
    onCodeChange?.(val)
  }

  return (
    <AuthLayout>
      <AuthHeader
        icon="shieldCheck"
        title="Two-step verification"
        subtitle="Enter the 6-digit code generated by your authenticator app."
      />

      <form onSubmit={onSubmit ?? ((e) => e.preventDefault())}>
        <Stack gap="md">
          <Center my="xs">
            <PinInput
              length={6}
              type="number"
              size="md"
              gap="xs"
              placeholder=""
              value={code}
              onChange={handleCodeChange}
              error={!!error}
              autoFocus
              className="two-factor-pin-input"
              styles={{
                input: {
                  width: '48px',
                  height: '56px',
                  fontSize: '1.25rem',
                  fontWeight: 600,
                  borderRadius: 'var(--radius-md)',
                  textAlign: 'center',
                },
              }}
            />
          </Center>

          {error && (
            <Text size="xs" c="var(--color-danger)" ta="center">
              {error}
            </Text>
          )}

          <Button
            type="submit"
            size="md"
            fullWidth
            loading={isLoading}
          >
            Verify and log in
          </Button>

          <Center>
            <Anchor
              component="button"
              type="button"
              size="sm"
              style={{ color: 'var(--text-link)', fontWeight: 500 }}
              onClick={onUseRecoveryCode}
            >
              Use a recovery code
            </Anchor>
          </Center>

          <Text size="xs" ta="center" mt="md" style={{ lineHeight: 1.5, color: 'var(--text-muted)' }}>
            Can't log in? Contact an administrator to reset your second factor.
          </Text>
        </Stack>
      </form>

      <style>{`
        @media (max-width: 420px) {
          .two-factor-pin-input input {
            width: 38px !important;
            height: 48px !important;
            font-size: 1.1rem !important;
          }
        }
      `}</style>
    </AuthLayout>
  )
}
